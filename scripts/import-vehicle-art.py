"""Audit the pinned Noto SVG paths and compile shared Canvas/SVG geometry.

No upstream scripts are run. Input is deliberately restricted to static paths.
"""
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/assets/vehicles/noto'
PAINT = {
    'city': {'#F92612': 'paint', '#D70617': 'shade', '#AF0F21': 'deep'},
    'touring': {'#489DF6': 'paint', '#1D86FB': 'shade', '#0250AC': 'deep'},
    'sport': {'#FF2A23': 'paint', '#B50D22': 'shade', '#CF1A35': 'deep', '#8C1D0B': 'deep', '#F8A128': 'accent'},
}
NEUTRALS = {'#AFE3FB': '#cbe6e9', '#546D81': '#3e5964', '#506D73': '#3e5964',
            '#4E433D': '#29363d', '#4C443F': '#29363d', '#4C4038': '#29363d',
            '#C8C8C8': '#dce3e4', '#858583': '#c3d1d4', '#31322E': '#29363d'}
HUBS = {'city': {10: [32, 110], 12: [102, 110.4]},
        'touring': {4: [27.8, 110.4], 6: [94.5, 110.2]},
        'sport': {14: [32.6, 108.4], 17: [102.1, 108.4]}}


def read_vehicle(body):
    file = SOURCE / f'{body}.svg'
    source = file.read_text(encoding='utf-8')
    if re.search(r'<!DOCTYPE|<!ENTITY|<script|<foreignObject|\bon\w+\s*=|(?:href|src)\s*=', source, re.I):
        raise ValueError(f'Active or external content in {file.name}')
    root = ET.fromstring(source)
    if root.attrib.get('viewBox') != '0 0 128 128':
        raise ValueError(f'Unexpected source canvas: {file.name}')
    paths = []
    for index, element in enumerate(root):
        if element.tag != '{http://www.w3.org/2000/svg}path' or set(element.attrib) - {'d', 'style'}:
            raise ValueError(f'Unexpected SVG element or attributes: {file.name}')
        match = re.fullmatch(r'fill:(#[A-Fa-f0-9]{6});', element.attrib['style'])
        if not match:
            raise ValueError(f'Unexpected SVG style: {file.name}')
        color = match[1].upper()
        d = re.sub(r'\s+', ' ', element.attrib['d']).strip()
        paths.append({'d': d, 'fill': PAINT[body].get(color, NEUTRALS.get(color, color)),
                      **({'pivot': HUBS[body][index]} if index in HUBS[body] else {})})
    digest = hashlib.sha256(file.read_bytes()).hexdigest()
    print(f'PASS {file.name}: {len(paths)} static paths, no external/active content, SHA256 {digest}')
    return paths


if __name__ == '__main__':
    data = {body: read_vehicle(body) for body in PAINT}
    output = '// Generated by scripts/import-vehicle-art.py from audited, pinned Noto SVG assets.\n'
    output += 'export interface VectorPath { d: string; fill: string; pivot?: number[] }\n'
    output += 'export const SIDE_PATHS: Record<string, VectorPath[]> = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'src/vehicle-paths.ts').write_text(output, encoding='utf-8')
